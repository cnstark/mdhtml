const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');
const {execFileSync, spawnSync} = require('node:child_process');

const root = path.resolve(__dirname, '..');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mdhtml-roundtrip-'));
try {
  const input = path.join(dir, 'source.md');
  const output = path.join(dir, 'source.md.html');
  const saved = path.join(dir, 'saved.md.html');
  const markdown = '# 中文 & <标题> "引号"\n\n原样保留 </script>、<\\/script>、\\\\ 和 emoji 🌿\n';
  const notes = [{id:'urn:uuid:123e4567-e89b-42d3-a456-426614174000', type:'Annotation', created:'2026-10-27T12:00:00.000Z', body:[{type:'TextualBody', value:'**批注** </script> --> ![图](asset.png) & "引号" \\ 🌿', format:'text/markdown', created:'2026-10-27T12:00:00.000Z'}, {type:'TextualBody', value:'第二轮回复', format:'text/markdown', created:'2026-10-27T12:01:00.000Z'}], target:{selector:[{type:'TextQuoteSelector', exact:'中文', prefix:'', suffix:' & <标题> "引号"'}, {type:'TextPositionSelector', start:0, end:2}]}}];
  const oldNotes = [{...notes[0], body:{type:'TextualBody', value:'旧批注', format:'text/markdown'}}];
  fs.writeFileSync(input, markdown);
  execFileSync('python3', [path.join(root, 'mdhtml'), 'build', input, '-o', output]);
  const built = fs.readFileSync(output, 'utf8');
  assert.equal(built.includes('<script id="annotations"'), false);
  const legacy = path.join(dir, 'legacy.md.html');
  fs.writeFileSync(legacy, built.replace('<header>', `<script id="annotations" type="application/json">${JSON.stringify(oldNotes).replace(/<\/script/gi, '<\\/script')}<\/script>\n<header>`));
  const legacyCheck = spawnSync('python3', [path.join(root, 'mdhtml'), 'check', legacy], {encoding:'utf8'});
  assert.equal(legacyCheck.status, 0);
  assert.match(legacyCheck.stderr, /旧 #annotations/);
  const migrated = execFileSync('python3', [path.join(root, 'mdhtml'), 'extract', legacy], {encoding:'utf8', stdio:['ignore', 'pipe', 'pipe']});
  assert.deepEqual(JSON.parse(migrated.match(/<!-- mdhtml-annotations\n([\s\S]*?)\n-->\n?$/)[1]), oldNotes);
  const base64 = built.match(/const TEMPLATE_BASE64 = "([^"]+)";/)[1];
  const template = fs.readFileSync(path.join(root, 'template.html'), 'utf8');
  const app = template.match(/<script id="mdhtml-app">\n([\s\S]*?)<\/script>/)[1];
  const functions = app.slice(app.indexOf('function escapeMarkdown('), app.indexOf('function downloadHtml('));
  const context = {TEMPLATE_BASE64: base64, TEMPLATE: Buffer.from(base64, 'base64').toString('utf8'), viewerScript: null};
  vm.createContext(context);
  vm.runInContext(functions, context);
  context.oldAnnotated = vm.runInContext('writeAnnotations(markdown, oldNotes)', Object.assign(context, {markdown, oldNotes}));
  assert.deepEqual(JSON.parse(context.oldAnnotated.match(/<!-- mdhtml-annotations\n([\s\S]*?)\n-->\n?$/)[1]), [{...oldNotes[0], body:[{...oldNotes[0].body, created:oldNotes[0].created}]}]);
  assert.deepEqual(JSON.parse(JSON.stringify(vm.runInContext('readAnnotations(oldAnnotated).notes', context))), [{...oldNotes[0], body:[{...oldNotes[0].body, created:oldNotes[0].created}]}]);
  const annotated = vm.runInContext('writeAnnotations(markdown, notes)', Object.assign(context, {markdown, notes}));
  fs.writeFileSync(path.join(dir, 'asset.png'), 'image bytes');
  fs.writeFileSync(input, annotated);
  const annotatedBuild = spawnSync('python3', [path.join(root, 'mdhtml'), 'build', input, '-o', output, '--embed-images'], {encoding:'utf8'});
  assert.equal(annotatedBuild.status, 0);
  assert.equal(execFileSync('python3', [path.join(root, 'mdhtml'), 'extract', output], {encoding:'utf8'}), annotated);
  assert.deepEqual(JSON.parse(annotated.match(/<!-- mdhtml-annotations\n([\s\S]*?)\n-->\n?$/)[1]), notes);
  assert.equal(vm.runInContext('readAnnotations(annotated).invalid', Object.assign(context, {annotated})), false);
  const html = vm.runInContext('serialize(annotated)', context);
  fs.writeFileSync(saved, html);
  const extracted = execFileSync('python3', [path.join(root, 'mdhtml'), 'extract', saved], {encoding: 'utf8'});
  assert.equal(extracted, annotated);
  assert.equal(html.includes('<script id="annotations"'), false);
  assert.deepEqual(JSON.parse(extracted.match(/<!-- mdhtml-annotations\n([\s\S]*?)\n-->\n?$/)[1]), notes);
  assert.equal((html.match(/<script id="md-source" type="text\/markdown">([\s\S]*?)<\/script>/) || [])[1].includes('</script>'), false);
  context.broken = 'x\n\n<!-- mdhtml-annotations\n{broken}\n-->\n';
  assert.equal(vm.runInContext('readAnnotations(broken).invalid', context), true);
  execFileSync('python3', [path.join(root, 'mdhtml'), 'check', saved]);
  console.log('serialize → CLI extract/check: OK');
} finally {
  fs.rmSync(dir, {recursive:true, force:true});
}
